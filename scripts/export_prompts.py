"""Writes Companion/App/SystemPrompt.swift from neuron-explorer/sweep/supporter_systems.py, so the app's prompts stay
identical to the evaluated ones. Run from app/: python3 scripts/export_prompts.py"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "neuron-explorer", "sweep"))
from supporter_systems import SYSTEMS  # noqa: E402

PROMPTS = {"friend": "friend_short", "calm": "calm5"}


def swift_literal(s):
    assert '"""' not in s and "\\" not in s
    return '"""\n' + "\n".join(("        " + ln) if ln else "" for ln in s.split("\n")) + '\n        """'


out = ['// Generated by scripts/export_prompts.py from neuron-explorer/sweep/supporter_systems.py. Do not edit by hand:',
       '// change the Python prompts, re-run the evals, then re-export.', '',
       "/// The chat model's system prompts, picked per message by the crisis layer's level (2026-11-02 evals):",
       "/// `friend` for messages rated none, `calm` for check-in. Crisis messages never reach the model.",
       "enum SystemPrompt {"]
for name, key in PROMPTS.items():
    text = SYSTEMS[key]
    out += [f"    /// `{key}`, sha256 {hashlib.sha256(text.encode()).hexdigest()[:16]}",
            f"    static let {name} = {swift_literal(text)}", ""]
out[-1] = "}"
path = os.path.join(HERE, "..", "Companion", "App", "SystemPrompt.swift")
open(path, "w").write("\n".join(out) + "\n")
print("->", os.path.normpath(path))
